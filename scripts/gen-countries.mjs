// Regenerates src/data/countries.generated.ts from the `world-countries` dataset.
// Run with `npm run gen:countries`. The output is committed; world-countries is only a
// build-time (dev) dependency, so the app ships a static, self-contained dataset.
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const require = createRequire(import.meta.url)
const countries = require('world-countries')
const outFile = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'countries.generated.ts')

/** Collapse world-countries' 6 regions into the classic 7 continents (Americas → N/S). */
function toContinent(region, subregion) {
  switch (region) {
    case 'Africa':
      return 'Africa'
    case 'Europe':
      return 'Europe'
    case 'Asia':
      return 'Asia'
    case 'Oceania':
      return 'Oceania'
    case 'Antarctic':
      return 'Antarctica'
    case 'Americas':
      return subregion === 'South America' ? 'South America' : 'North America'
    default:
      return 'Other'
  }
}

const rows = countries
  .map((c) => ({
    a3: c.cca3,
    // world-atlas feature ids are the ISO numeric code with leading zeros stripped.
    numericId: c.ccn3 ? String(Number(c.ccn3)) : '',
    name: c.name.common,
    continent: toContinent(c.region, c.subregion),
    subregion: c.subregion || 'Other',
    flag: c.flag || '',
    counts: c.unMember === true,
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

const header = `// AUTO-GENERATED by scripts/gen-countries.mjs from the \`world-countries\` dataset.
// Do not edit by hand — run \`npm run gen:countries\` to regenerate.

export type Continent =
  | 'Africa'
  | 'Asia'
  | 'Europe'
  | 'North America'
  | 'South America'
  | 'Oceania'
  | 'Antarctica'
  | 'Other'

export type Country = {
  a3: string // ISO 3166-1 alpha-3 — the key for persisted state
  numericId: string // ISO 3166-1 numeric, leading zeros stripped (matches world-atlas feature ids)
  name: string
  continent: Continent
  subregion: string
  flag: string // emoji
  counts: boolean // UN member — counts toward the "% of the world" denominator
}

export const COUNTRIES: Country[] = ${JSON.stringify(rows, null, 2)}
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, header)
console.log(`Wrote ${rows.length} countries to ${outFile}`)
